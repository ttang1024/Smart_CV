const normalizeDemoLocale = (language?: string): DemoLocale => {
	if (!language) return 'en'
	if (language.startsWith('zh-TW')) return 'zh-TW'
	if (language.startsWith('zh-CN') || language.startsWith('zh')) return 'zh-CN'
	if (language.startsWith('es')) return 'es'
	return 'en'
}

